"""Preserve the user PDF, render final masters, and audit editable output."""
from pathlib import Path
import argparse
import hashlib
import json
import re
import shutil
import sys
import xml.etree.ElementTree as ET

import numpy as np
import pandas as pd
from PIL import Image, ImageDraw
import pymupdf as fitz

ROOT=Path(__file__).resolve().parents[1]
layout=json.loads((ROOT/'config/layout.json').read_text())
mm=72/25.4
fig_names=['Figure1_data','Figure2','FigureS1','FigureS2','FigureS3','FigureS4']
results=[];spans_out=[]

def audit(name,test,passed,detail=''):
    results.append(dict(figure=name,check=test,status='PASS' if passed else 'WARNING',details=detail))

source=ROOT/'assets/Figure1A_user_original.pdf'
manifest=pd.read_csv(ROOT/'provenance/INPUT_MANIFEST.tsv',sep='\t')
original_hash=manifest.loc[manifest.staged_file=='assets/Figure1A_user_original.pdf','sha256'].iloc[0]
assert hashlib.sha256(source.read_bytes()).hexdigest()==original_hash
user=fitz.open(source)
a_rect=layout['Figure1']['panels']['A']
ar=user[0].rect.height/user[0].rect.width
target=[a_rect[0],a_rect[1],a_rect[2],a_rect[2]*ar]
src_spans=[s for b in user[0].get_text('dict')['blocks'] if 'lines' in b
           for ln in b['lines'] for s in ln['spans']]
min_original=min(s['size'] for s in src_spans)
scaled_min=min_original*target[2]*mm/user[0].rect.width
composition=dict(user_source='assets/Figure1A_user_original.pdf',sha256=original_hash,
                 source_width_pt=user[0].rect.width,source_height_pt=user[0].rect.height,
                 destination_mm=target,keep_proportion=True,internal_modification=False,
                 minimum_original_font_pt=min_original,minimum_composed_font_pt=scaled_min,
                 deliverable_status='Reference composition only; original A is too small in this compact slot',
                 data_master='figures/Figure1_data.pdf',editable_data_svg='figures/Figure1_data.svg')
(ROOT/'config/Figure1A_composition.json').write_text(json.dumps(composition,indent=2)+'\n')
data=fitz.open(ROOT/'figures/Figure1_data.pdf')
composed=fitz.open();page=composed.new_page(width=data[0].rect.width,height=data[0].rect.height)
page.show_pdf_page(page.rect,data,0)
rect=fitz.Rect(target[0]*mm,target[1]*mm,(target[0]+target[2])*mm,(target[1]+target[3])*mm)
page.show_pdf_page(rect,user,0,keep_proportion=True)
composed.set_metadata({'title':'Reference composition: original user Figure 1A + redrawn data',
                      'subject':'Original A untouched; compact A text below target size; see QA report.'})
composed.save(ROOT/'figures/Figure1_with_original_A_reference.pdf')
composed[0].get_pixmap(dpi=180,alpha=False).save(ROOT/'preview/Figure1_with_original_A_reference.png')
audit('Figure1A','Original asset SHA256 unchanged',True,original_hash)
audit('Figure1A','Final-size lettering',False,f'Protected asset reaches {scaled_min:.2f} pt in A slot; reference preview only.')

for name in fig_names:
    doc=fitz.open(ROOT/'figures'/f'{name}.pdf');page=doc[0]
    config_name='Figure1' if name=='Figure1_data' else name
    expected=layout[config_name]['size_mm']
    actual=[page.rect.width/mm,page.rect.height/mm]
    audit(name,'Physical dimensions',np.allclose(actual,expected,atol=.01),str(actual))
    spans=[s for b in page.get_text('dict')['blocks'] if 'lines' in b for ln in b['lines'] for s in ln['spans']]
    for s in spans:
        spans_out.append(dict(figure=name,text=s['text'],size_pt=s['size'],font=s['font'],bbox=str(s['bbox'])))
    # Superscript numerals generated by the math formatter are smaller by design;
    # audit ordinary text independently and report all glyph sizes in the TSV.
    normal=[s for s in spans if re.search(r'[A-Za-z]',s['text'])]
    min_size=min(s['size'] for s in normal)
    audit(name,'Ordinary lettering at least 5 pt',min_size>=4.99,f'min ordinary text={min_size:.3f} pt')
    outside=[s['text'] for s in spans if s['bbox'][0]<-.5 or s['bbox'][1]<-.5 or
             s['bbox'][2]>page.rect.width+.5 or s['bbox'][3]>page.rect.height+.5]
    audit(name,'Text inside page',not outside,'; '.join(outside))
    expected_letters=list(layout[config_name]['panels'])
    if config_name=='Figure1':expected_letters.remove('A')
    present={s['text'].strip() for s in spans}
    audit(name,'All data-panel letters present',set(expected_letters)<=present,','.join(expected_letters))
    if config_name=='Figure1':
        a=fitz.Rect(*(v*mm for v in [target[0],target[1],target[0]+target[2],target[1]+target[3]]))
        audit(name,'Protected A slot empty in editable data master',page.get_text(clip=a).strip()=='')
    fonts=page.get_fonts(full=True)
    audit(name,'No Type 3 fonts',not any(f[2]=='Type3' for f in fonts),str([(f[2],f[3]) for f in fonts]))
    audit(name,'Fonts embedded',all(f[1]!='n/a' for f in fonts),str([f[1] for f in fonts]))
    tree=ET.parse(ROOT/'figures'/f'{name}.svg')
    ns={'s':'http://www.w3.org/2000/svg'}
    ntext=len(tree.findall('.//s:text',ns));nimage=len(tree.findall('.//s:image',ns))
    audit(name,'SVG editable text exists',ntext>20,f'{ntext} text nodes; {nimage} raster data-layer elements')
    if name=='Figure2':
        labels=pd.read_csv(ROOT/'source_data/panels/Figure2A_labels.csv',float_precision='round_trip')
        frozen=pd.read_csv(ROOT/'source_data/archived/lmm.tsv.gz',sep='\t',float_precision='round_trip').set_index('feature_id')
        match=frozen.loc[labels.feature_id]
        audit(name,'Each volcano arrow matches full-key effect and BH q',
              np.array_equal(labels.target_x.values,match.estimate.values) and
              np.allclose(labels.target_y.values,-np.log10(match.q_value.values),rtol=0,atol=1e-14),
              '8 original LR features; exact saved estimate / -log10(q) targets')
        ids={element.attrib.get('id') for element in tree.iter()}
        audit(name,'All eight editable volcano leaders exported',
              {'leader_'+v for v in labels.display_id}<=ids)
    im=Image.open(ROOT/'figures'/f'{name}.png')
    expected_px=np.array(expected)/25.4*600
    audit(name,'600 dpi at final physical size',np.allclose(im.size,expected_px,atol=2),str(im.size))
    page.get_pixmap(dpi=180,alpha=False).save(ROOT/'preview'/f'{name}_from_pdf.png')

# PDF crop previews for high-density areas, rendered from the actual master.
for name,letter in [('Figure2','A'),('Figure2','C'),('Figure2','D'),('Figure2','E'),
                    ('Figure1_data','B'),('Figure1_data','C'),('Figure1_data','G')]:
    config_name='Figure1' if name=='Figure1_data' else name
    x,y,w,h=layout[config_name]['panels'][letter]
    doc=fitz.open(ROOT/'figures'/f'{name}.pdf')
    doc[0].get_pixmap(dpi=300,clip=fitz.Rect(x*mm,y*mm,(x+w)*mm,(y+h)*mm),alpha=False).save(
        ROOT/'preview'/f'{name}{letter}_detail.png')

try:
    from colorspacious import cspace_convert
    cvd_available=True
except ImportError:
    cvd_available=False

for name in fig_names:
    original=Image.open(ROOT/'preview'/f'{name}_from_pdf.png').convert('RGB')
    original.thumbnail((540,650))
    rgb=np.asarray(original)/255.0
    gray=Image.fromarray(np.repeat(np.asarray(original.convert('L'))[:,:,None],3,axis=2))
    images=[original,gray];labels=['Original','Grayscale']
    if cvd_available:
        for typ,label in [('deuteranomaly','Deuteranopia simulation'),('protanomaly','Protanopia simulation')]:
            simulated=cspace_convert(rgb,{'name':'sRGB1+CVD','cvd_type':typ,'severity':100},'sRGB1')
            images.append(Image.fromarray(np.uint8(np.clip(simulated,0,1)*255)));labels.append(label)
    sheet=Image.new('RGB',(original.width*len(images),original.height+25),'white')
    draw=ImageDraw.Draw(sheet)
    for i,(im,label) in enumerate(zip(images,labels)):
        sheet.paste(im,(i*original.width,25));draw.text((i*original.width+5,5),label,fill='black')
    sheet.save(ROOT/'preview'/f'{name}_color_vision.png')
    audit(name,'Color-vision simulations generated',cvd_available,'Visual review required; generated images are not automatic proof of discriminability.')

pd.DataFrame(results).to_csv(ROOT/'reports/export_checks.tsv',sep='\t',index=False)
pd.DataFrame(spans_out).to_csv(ROOT/'reports/PDF_TEXT_AUDIT.tsv',sep='\t',index=False)
print(pd.DataFrame(results).groupby('status').size().to_string())
print('Protected A reference only: minimum lettering',scaled_min)
